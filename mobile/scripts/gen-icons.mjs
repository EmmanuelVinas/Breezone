// Generates FzIcons.kt (Compose ImageVectors) from the Lucide icons used by the web UI,
// so that web and mobile share the same iconography without a heavy icon dependency.
//   node mobile/scripts/gen-icons.mjs   (needs web/node_modules)
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..")
const lucide = resolve(root, "web/node_modules/lucide-react/dist/esm/icons")
const out = resolve(root, "mobile/shared/src/commonMain/kotlin/com/breezone/app/ui/icons/FzIcons.kt")

const ICONS = [
  "flame", "snowflake", "fan", "droplets", "droplet", "power", "sparkles", "heater", "moon", "wind",
  "thermometer", "map-pin", "plus", "minus", "chevron-right", "chevron-left", "house", "calendar-clock",
  "settings", "cloud", "cloud-off", "refresh-cw", "play", "trash-2", "pencil", "log-out", "server",
  "battery-warning", "triangle-alert", "check", "x", "clock", "radar", "user", "eye", "eye-off",
  "circle-check", "wifi-off", "activity", "list-plus", "leaf",
]

const n = (v) => Number(v)
function toPath(tag, a) {
  switch (tag) {
    case "path":
      return a.d
    case "line":
      return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`
    case "circle": {
      const [cx, cy, r] = [n(a.cx), n(a.cy), n(a.r)]
      return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`
    }
    case "ellipse": {
      const [cx, cy, rx, ry] = [n(a.cx), n(a.cy), n(a.rx), n(a.ry)]
      return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0`
    }
    case "rect": {
      const [x, y, w, h] = [n(a.x), n(a.y), n(a.width), n(a.height)]
      const r = Math.min(n(a.rx ?? a.ry ?? 0), w / 2, h / 2)
      if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`
      return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`
    }
    case "polyline":
    case "polygon": {
      const pts = a.points.trim().split(/[\s,]+/).map(Number)
      let d = `M${pts[0]} ${pts[1]}`
      for (let i = 2; i < pts.length; i += 2) d += `L${pts[i]} ${pts[i + 1]}`
      return tag === "polygon" ? d + "Z" : d
    }
    default:
      throw new Error(`unsupported SVG element ${tag}`)
  }
}

const camel = (s) => s.split("-").map((p) => p[0].toUpperCase() + p.slice(1)).join("")
let body = ""
for (const name of ICONS) {
  // Some names are aliases re-exporting another icon file: follow them.
  let file = resolve(lucide, `${name}.mjs`)
  const alias = readFileSync(file, "utf8").match(/from '\.\/([^']+\.mjs)'/)
  if (!readFileSync(file, "utf8").includes("__iconData") && alias) file = resolve(lucide, alias[1])
  const mod = await import(pathToFileURL(file).href)
  const paths = mod.__iconData.node.map(([tag, attrs]) => toPath(tag, attrs))
  const list = paths.map((p) => `"${p}"`).join(",\n            ")
  body += `    val ${camel(name)}: ImageVector by lazy {\n        lucide(\n            "${camel(name)}",\n            ${list},\n        )\n    }\n\n`
}

const kt = `// Generated by mobile/scripts/gen-icons.mjs from Lucide (ISC license). Do not edit.
package com.breezone.app.ui.icons

import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

/** Stroke icons (24×24, stroke 2) — tinted by Icon(). */
private fun lucide(name: String, vararg paths: String): ImageVector =
    ImageVector.Builder(name = name, defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 24f, viewportHeight = 24f)
        .apply {
            paths.forEach { d ->
                addPath(
                    pathData = addPathNodes(d),
                    fill = null,
                    stroke = SolidColor(Color.Black),
                    strokeLineWidth = 2f,
                    strokeLineCap = StrokeCap.Round,
                    strokeLineJoin = StrokeJoin.Round,
                )
            }
        }
        .build()

object FzIcons {
${body.trimEnd()}
}
`
writeFileSync(out, kt)
console.log(`${ICONS.length} icons → ${out}`)
