#!/usr/bin/env node
// The licences of the libraries in the app: those of the Android release build (the iOS app uses
// the same ones, with Ktor's Darwin engine instead of OkHttp), read from their Maven POM files.
// Writes shared/src/commonMain/composeResources/files/third-party-licenses.txt, shown in
// Settings › Licences. Run it from mobile/ after changing a dependency:
//
//   node scripts/third-party-licenses.mjs

import { execFileSync } from "node:child_process"
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import { homedir } from "node:os"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const mobile = join(dirname(fileURLToPath(import.meta.url)), "..")
const out = join(mobile, "shared/src/commonMain/composeResources/files/third-party-licenses.txt")
const cache = join(process.env.GRADLE_USER_HOME ?? join(homedir(), ".gradle"), "caches/modules-2/files-2.1")

const tree = execFileSync("./gradlew", ["-q", ":androidApp:dependencies", "--configuration", "releaseRuntimeClasspath"], {
  cwd: mobile,
  maxBuffer: 64 * 1024 * 1024,
}).toString()

/** group:name → the version resolved (after "->"), constraints "(c)" left out. */
const resolved = new Map()
for (const line of tree.split("\n")) {
  const m = line.match(/[+\\]--- ([^\s:]+):([^\s:]+):?(\S*)(?: -> (\S+))?(.*)$/)
  if (!m || m[5].includes("(c)") || m[1] === "project") continue
  const version = m[4] ?? m[3]
  if (version) resolved.set(`${m[1]}:${m[2]}`, version)
}

/** The POM of a module, from the Gradle cache. */
function pom(group, name, version) {
  const dir = join(cache, group, name, version)
  if (!existsSync(dir)) return null
  for (const hash of readdirSync(dir)) {
    const file = join(dir, hash, `${name}-${version}.pom`)
    if (existsSync(file)) return readFileSync(file, "utf8")
  }
  return null
}

/** Files of a module's archive (jar or aar) matching `pattern`: its own licence or notice. */
function inArchive(group, name, version, pattern) {
  const dir = join(cache, group, name, version)
  if (!existsSync(dir)) return []
  for (const hash of readdirSync(dir)) {
    for (const ext of ["jar", "aar"]) {
      const file = join(dir, hash, `${name}-${version}.${ext}`)
      if (!existsSync(file)) continue
      try {
        const names = execFileSync("unzip", ["-Z1", file]).toString().split("\n").filter((f) => pattern.test(f))
        return names.map((f) => execFileSync("unzip", ["-p", file, f]).toString().replace(/\r\n/g, "\n").trim()).filter(Boolean)
      } catch {
        return []
      }
    }
  }
  return []
}

const tag = (xml, t) => xml.match(new RegExp(`<${t}>\\s*([\\s\\S]*?)\\s*</${t}>`))?.[1]

/** The licences a POM declares, or its parent's. */
function licenses(group, name, version, depth = 0) {
  const xml = pom(group, name, version)
  if (!xml) return []
  const block = tag(xml, "licenses")
  if (block) {
    return [...block.matchAll(/<license>([\s\S]*?)<\/license>/g)].map((l) => ({ name: tag(l[1], "name") ?? "?", url: tag(l[1], "url") ?? "" }))
  }
  const parent = tag(xml, "parent")
  if (parent && depth < 5) return licenses(tag(parent, "groupId"), tag(parent, "artifactId"), tag(parent, "version"), depth + 1)
  return []
}

/** Modules published with Gradle metadata only (no POM in the cache): their families' licence. */
const KNOWN = [
  ["androidx.", "The Apache Software License, Version 2.0"],
  ["org.jetbrains.", "The Apache Software License, Version 2.0"],
  ["co.touchlab", "The Apache Software License, Version 2.0"],
  ["com.google.guava", "The Apache Software License, Version 2.0"],
]

const lines = [
  "Breezone — licences of the libraries in the app",
  "",
  "Breezone itself is under the PolyForm Noncommercial License 1.0.0.",
  "It is built with the open source libraries below, each under its own licence.",
  "Generated by mobile/scripts/third-party-licenses.mjs: do not edit by hand.",
  "",
]
const unknown = []
const texts = new Map()
for (const [module, version] of [...resolved].sort(([a], [b]) => a.localeCompare(b))) {
  const [group, name] = module.split(":")
  let found = licenses(group, name, version)
  if (found.length === 0) {
    const known = KNOWN.find(([prefix]) => group.startsWith(prefix))
    if (known) found = [{ name: known[1], url: "" }]
    else unknown.push(module)
  }
  lines.push(`${module} ${version} — ${found.map((l) => l.name).join(" / ") || "see the project"}`)
  // The notices Apache asks to pass on, and the texts of the other licences (with their copyright).
  const apache = found.length > 0 && found.every((l) => /apache/i.test(l.name))
  const pattern = apache ? /^META-INF\/NOTICE[^/]*$/i : /^META-INF\/(LICENSE|NOTICE)[^/]*$/i
  for (const text of inArchive(group, name, version, pattern)) {
    if (![...texts.values()].includes(text)) texts.set(`${module} ${version}`, text)
  }
}
if (texts.size) {
  lines.push("", "=".repeat(78), "Notices and other licences", "=".repeat(78))
  for (const [module, text] of texts) lines.push("", `--- ${module} ${"-".repeat(40)}`, "", text)
}
lines.push("", "=".repeat(78), "Apache License 2.0 (the licence of most of the libraries above)", "=".repeat(78), "")
lines.push(readFileSync(join(mobile, "scripts/apache-2.0.txt"), "utf8").trim(), "")

mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, lines.join("\n"))
console.log(`${out}: ${resolved.size} libraries`)
if (unknown.length) console.log(`without a licence in their POM: ${unknown.join(", ")}`)
