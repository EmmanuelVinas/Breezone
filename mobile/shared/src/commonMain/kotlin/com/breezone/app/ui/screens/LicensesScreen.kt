/** The licences of the libraries in the app (generated by mobile/scripts/third-party-licenses.mjs). */
@OptIn(ExperimentalResourceApi::class)
@Composable
fun LicensesScreen(onBack: () -> Unit) {
    var lines by remember { mutableStateOf<List<String>?>(null) }
    LaunchedEffect(Unit) {
        val text = runCatching { Res.readBytes("files/third-party-licenses.txt").decodeToString() }.getOrDefault("")
        // The file's own header says what the intro says.
        lines = text.lines().dropWhile { it.isNotBlank() }.dropWhile { it.isBlank() }.let { rest -> rest.dropWhile { it.isNotBlank() } }.dropWhile { it.isBlank() }
    }
    Scaffold(topBar = { FzTopBar(stringResource(Res.string.settings_licenses), null, onBack) }) { padding ->
        val shown = lines
        if (shown == null) {
            Box(Modifier.fillMaxSize().padding(padding), contentAlignment = Alignment.Center) { LoadingWave() }
            return@Scaffold
        }
        LazyColumn(
            Modifier.fillMaxSize(),
            contentPadding = PaddingValues(start = 16.dp, end = 16.dp, top = padding.calculateTopPadding() + 4.dp, bottom = 24.dp),
        ) {
            item(key = "intro", contentType = "intro") { Muted(stringResource(Res.string.licenses_intro), Modifier.padding(bottom = 12.dp)) }
            itemsIndexed(shown, key = { i, _ -> i }, contentType = { _, _ -> "line" }) { _, line ->
                Text(
                    line,
                    style = MaterialTheme.typography.bodySmall.copy(fontFamily = FontFamily.Monospace, fontSize = 11.sp, lineHeight = 15.sp),
                    color = if (line.startsWith("=") || line.startsWith("---")) Fz.colors.muted else MaterialTheme.colorScheme.onSurface,
                )
            }
        }
    }
}
