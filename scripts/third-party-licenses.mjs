#!/usr/bin/env node
// The licences of what Breezone ships: the crates of the server and the npm packages of the web UI.
// Writes web/public/third-party-licenses.txt, served with the web UI (so it is in the Docker image
// and in the self-update archive). Run it after changing a dependency:
//
//   node scripts/third-party-licenses.mjs           # write the file
//   node scripts/third-party-licenses.mjs --check   # fail when the file is not up to date (CI)

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "web/public/third-party-licenses.txt");
const LICENSE_FILE =
  /^(licen[cs]e|copying|notice|copyright|unlicense)([-_.].*)?$/i;

/** The licence texts of a package directory, by file name. */
function texts(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f))
    .sort()
    .map((f) => ({
      file: f,
      text: readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n").trim(),
    }))
    .filter((t) => t.text);
}

/** The crates the server binary is built from: normal dependencies, followed from the server. */
function crates() {
  const meta = JSON.parse(
    execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], {
      cwd: join(root, "server"),
      maxBuffer: 256 * 1024 * 1024,
    }),
  );
  const byId = new Map(meta.packages.map((p) => [p.id, p]));
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
  const seen = new Set();
  const todo = [...meta.workspace_members];
  while (todo.length) {
    const id = todo.pop();
    if (seen.has(id)) continue;
    seen.add(id);
    for (const d of nodes.get(id)?.deps ?? []) {
      if (d.dep_kinds.some((k) => k.kind === null)) todo.push(d.pkg);
    }
  }
  return [...seen]
    .map((id) => byId.get(id))
    .filter((p) => p.source !== null)
    .map((p) => ({
      name: p.name,
      version: p.version,
      license:
        p.license ?? (p.license_file ? `see ${p.license_file}` : "unknown"),
      url: p.repository ?? p.homepage ?? null,
      texts: texts(dirname(p.manifest_path)),
    }));
}

/** The npm packages of the web UI (not the development tools). */
function packages() {
  const lock = JSON.parse(
    readFileSync(join(root, "web/package-lock.json"), "utf8"),
  );
  return (
    Object.entries(lock.packages)
      // Binaries for one system (os/cpu) are build tools, and differ from one machine to another.
      .filter(
        ([path, p]) => path && !p.dev && !p.devOptional && !p.os && !p.cpu,
      )
      .map(([path, p]) => {
        const dir = join(root, "web", path);
        const manifest = existsSync(join(dir, "package.json"))
          ? JSON.parse(readFileSync(join(dir, "package.json"), "utf8"))
          : {};
        const repo =
          typeof manifest.repository === "string"
            ? manifest.repository
            : manifest.repository?.url;
        return {
          name: path.split("node_modules/").pop(),
          version: p.version,
          license:
            (typeof p.license === "string" ? p.license : p.license?.type) ??
            manifest.license ??
            "unknown",
          url: repo ?? manifest.homepage ?? null,
          texts: texts(dir),
        };
      })
  );
}

function section(title, list, shared) {
  const lines = [
    `${"=".repeat(78)}\n${title} (${list.length})\n${"=".repeat(78)}\n`,
  ];
  const seen = new Set();
  for (const p of list.sort(
    (a, b) =>
      a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
  )) {
    const key = `${p.name}@${p.version}`;
    if (seen.has(key)) continue;
    seen.add(key);
    lines.push(
      `${p.name} ${p.version} — ${p.license}${p.url ? `\n  ${p.url}` : ""}`,
    );
    if (p.texts.length === 0)
      lines.push("  (no licence file in the package: see its licence above)");
    for (const t of p.texts) {
      const hash = createHash("sha256")
        .update(t.text)
        .digest("hex")
        .slice(0, 12);
      if (!shared.has(hash)) shared.set(hash, t.text);
      lines.push(`  ${t.file}: [text ${hash}]`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

const shared = new Map();
const body = [
  "Breezone — licences of the third-party software it includes",
  "",
  "Breezone itself is under the PolyForm Noncommercial License 1.0.0 (LICENSE.md).",
  "It is built with the open source software below, each under its own licence.",
  "Generated by scripts/third-party-licenses.mjs: do not edit by hand.",
  "",
  section("Server (Rust crates)", crates(), shared),
  section("Web interface (npm packages)", packages(), shared),
  `${"=".repeat(78)}\nLicence texts\n${"=".repeat(78)}\n`,
  ...[...shared].map(
    ([hash, text]) => `--- text ${hash} ${"-".repeat(60)}\n\n${text}\n`,
  ),
].join("\n");

if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (current !== body) {
    console.error(
      "web/public/third-party-licenses.txt is not up to date: run node scripts/third-party-licenses.mjs",
    );
    process.exit(1);
  }
} else {
  writeFileSync(out, body);
  console.log(
    `${out}: ${(body.length / 1024).toFixed(0)} KB, ${shared.size} licence texts`,
  );
}
